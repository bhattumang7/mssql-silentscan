using System.CommandLine;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateRescueMatrixCommand
{
    public static Command Create() =>
        MatrixCommandSupport.Create(
            "generate-rescue-matrix",
            "Compile predicate shapes that look non-sargable under table designs and constants that may let the optimizer rescue them, and record the plan.",
            "src/SilentScan.Core/Rules/RescueMatrix.json",
            RunAsync);

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var generator = new RescueMatrixGenerator(sqlOptions);
        var (cells, serverVersion) = await generator.GenerateAsync(RescueScenarios.All, cancellationToken);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = MatrixCommandSupport.ProbedAtUtc(),
            Notes = "Generated by SilentScan.Verify generate-rescue-matrix against the local Docker SQL Server. "
                + "Each cell compiles SELECT 1 (Outcome) and SELECT filler (OutcomeWithLookup) FROM t WHERE <predicate> over a table whose statistics claim a million rows and records the estimated plan: "
                + "Seek, Scan, or NoTableAccess when the optimizer proves the predicate empty without reading the table; +Convert marks a plan-affecting conversion warning.",
            Entries = cells,
        };

        return await MatrixCommandSupport.WriteAsync(outputPath, document, cells.Count, serverVersion, stdout, cancellationToken);
    }
}
