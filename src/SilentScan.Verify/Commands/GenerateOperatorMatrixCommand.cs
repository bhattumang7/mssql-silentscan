using System.CommandLine;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateOperatorMatrixCommand
{
    public static Command Create() =>
        MatrixCommandSupport.Create(
            "generate-operator-matrix",
            "Probe the Docker SQL Server oracle for the result type of every operator and branch-typing construct over every pair of operand types.",
            "src/SilentScan.Core/Rules/OperatorMatrix.json",
            RunAsync);

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var generator = new OperatorMatrixGenerator(sqlOptions);
        var (cells, serverVersion) = await generator.GenerateAsync(AssignMatrixGenerator.Types, cancellationToken);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = MatrixCommandSupport.ProbedAtUtc(),
            Notes = "Generated by SilentScan.Verify generate-operator-matrix against the local Docker SQL Server. "
                + "Each cell holds, in the order of Operators, the result type the engine reports for that operator over a variable of the left type and a variable of the right type. "
                + "Error:n means the engine rejects the pair with message n.",
            Operators = OperatorMatrixGenerator.Operators.Select(o => o.Name).ToList(),
            Entries = cells,
        };

        return await MatrixCommandSupport.WriteAsync(outputPath, document, cells.Count, serverVersion, stdout, cancellationToken);
    }
}
