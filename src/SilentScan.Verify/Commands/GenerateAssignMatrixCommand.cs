using System.CommandLine;
using System.Text.Json;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateAssignMatrixCommand
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    public static Command Create()
    {
        var outputOption = new Option<string>("--output")
        {
            Description = "Path to write the matrix JSON to.",
            DefaultValueFactory = _ => "src/SilentScan.Core/Rules/AssignMatrix.json",
        };

        var command = new Command("generate-assign-matrix", "Probe the Docker SQL Server oracle for what every source-to-target type assignment keeps or loses and write the checked-in matrix JSON.");
        command.Options.Add(outputOption);

        command.SetAction(async (parseResult, cancellationToken) =>
        {
            var output = parseResult.GetValue(outputOption)!;
            return await RunAsync(output, SqlServerOptions.LocalDocker, Console.Out, cancellationToken);
        });

        return command;
    }

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var generator = new AssignMatrixGenerator(sqlOptions);
        var (cells, serverVersion) = await generator.GenerateAsync(AssignMatrixGenerator.Types, AssignMatrixGenerator.Types, cancellationToken);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = DateTime.UtcNow.ToString("yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture),
            Notes = "Generated by SilentScan.Verify generate-assign-matrix against the local Docker SQL Server. "
                + "Each cell lists one outcome per probe value. Equal means the value read back through the target type equals the source value. "
                + "Loss means it differs (truncated, rounded, replaced or precision dropped) with no error. Error:n means the engine raised message n. "
                + "Variable is SET @t = @s; the Column contexts INSERT into a temp table column under SET ANSI_WARNINGS ON or OFF.",
            Entries = cells,
        };

        var json = JsonSerializer.Serialize(document, JsonOptions);
        await File.WriteAllTextAsync(outputPath, json + Environment.NewLine, cancellationToken);
        await stdout.WriteLineAsync($"Wrote {cells.Count} entries (server {serverVersion}) to {outputPath}");
        return 0;
    }
}
