using System.CommandLine;
using System.Text.Json;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateSargShapeMatrixCommand
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    public static Command Create()
    {
        var outputOption = new Option<string>("--output")
        {
            Description = "Path to write the matrix JSON to.",
            DefaultValueFactory = _ => "src/SilentScan.Core/Rules/SargShapeMatrix.json",
        };

        var command = new Command("generate-sarg-matrix", "Compile predicate shapes over an indexed column of each type on the Docker SQL Server oracle and record whether the plan seeks or scans.");
        command.Options.Add(outputOption);

        command.SetAction(async (parseResult, cancellationToken) =>
        {
            var output = parseResult.GetValue(outputOption)!;
            return await RunAsync(output, SqlServerOptions.LocalDocker, Console.Out, cancellationToken);
        });

        return command;
    }

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var generator = new SargShapeMatrixGenerator(sqlOptions);
        var (cells, serverVersion) = await generator.GenerateAsync(SargShapes.ColumnTypesWithNullability, SargShapes.All, cancellationToken);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = DateTime.UtcNow.ToString("yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture),
            Notes = "Generated by SilentScan.Verify generate-sarg-matrix against the local Docker SQL Server. "
                + "Each cell compiles SELECT c FROM t WHERE <shape> over a nonclustered-indexed column of the given type (nullable unless the type ends in NOT NULL) in a table whose statistics claim a million rows, and records the estimated plan: "
                + "Seek when the plan contains a seek predicate, Scan when it scans, with +Convert when the plan carries an implicit-conversion warning. Error:n means the engine rejects the shape for that type.",
            Entries = cells,
        };

        var json = JsonSerializer.Serialize(document, JsonOptions);
        await File.WriteAllTextAsync(outputPath, json + Environment.NewLine, cancellationToken);
        await stdout.WriteLineAsync($"Wrote {cells.Count} entries (server {serverVersion}) to {outputPath}");
        return 0;
    }
}
