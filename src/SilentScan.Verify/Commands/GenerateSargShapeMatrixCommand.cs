using System.CommandLine;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateSargShapeMatrixCommand
{
    public static Command Create() =>
        MatrixCommandSupport.Create(
            "generate-sarg-matrix",
            "Compile predicate shapes over an indexed column of each type on the Docker SQL Server oracle and record whether the plan seeks or scans.",
            "src/SilentScan.Core/Rules/SargShapeMatrix.json",
            RunAsync);

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var generator = new SargShapeMatrixGenerator(sqlOptions);
        var (cells, serverVersion) = await generator.GenerateAsync(SargShapes.ColumnTypesWithNullability, SargShapes.All, cancellationToken);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = MatrixCommandSupport.ProbedAtUtc(),
            Notes = "Generated by SilentScan.Verify generate-sarg-matrix against the local Docker SQL Server. "
                + "Each cell compiles SELECT c FROM t WHERE <shape> over a nonclustered-indexed column of the given type (nullable unless the type ends in NOT NULL) in a table whose statistics claim a million rows, and records the estimated plan: "
                + "Seek when the plan contains a seek predicate, Scan when it scans, with +Convert when the plan carries an implicit-conversion warning. Error:n means the engine rejects the shape for that type.",
            Entries = cells,
        };

        return await MatrixCommandSupport.WriteAsync(outputPath, document, cells.Count, serverVersion, stdout, cancellationToken);
    }
}
