using System.CommandLine;
using System.Text.Json;
using System.Text.Json.Serialization;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateScopeCorpusCommand
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() },
    };

    public static Command Create()
    {
        var outputOption = new Option<string>("--output")
        {
            Description = "Path to write the scope scenario corpus JSON to.",
            DefaultValueFactory = _ => "tests/SilentScan.Tests/fixtures/scope/ScopeScenarioCorpus.json",
        };

        var command = new Command("generate-scope-corpus", "Run every scope scenario on the Docker SQL Server oracle and write the observed bindings as a checked-in corpus.");
        command.Options.Add(outputOption);

        command.SetAction(async (parseResult, cancellationToken) =>
        {
            var output = parseResult.GetValue(outputOption)!;
            return await RunAsync(output, SqlServerOptions.LocalDocker, Console.Out, cancellationToken);
        });

        return command;
    }

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var runner = new ScopeScenarioRunner(sqlOptions);
        var (observations, serverVersion) = await runner.RunAsync(ScopeScenarios.All, cancellationToken);
        var observedById = observations.ToDictionary(o => o.Id, o => o.Observed);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = DateTime.UtcNow.ToString("yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture),
            Notes = "Generated by SilentScan.Verify generate-scope-corpus against the local Docker SQL Server. "
                + "Witness scenarios record the first value returned (or Error:n, or NULL, or NoRows). "
                + "Binding scenarios record the referenced entities the engine reports for the created module as schema.entity.column joined by semicolons; object names carry the scenario prefix replaced by P_. "
                + "{P} in Setup and Body is the per-scenario object-name prefix.",
            Entries = ScopeScenarios.All.Select(s => new
            {
                s.Id,
                s.Family,
                s.Step,
                s.Kind,
                s.CaseSensitiveDatabase,
                s.Setup,
                s.Body,
                Observed = observedById[s.Id],
            }),
        };

        var json = JsonSerializer.Serialize(document, JsonOptions);
        await File.WriteAllTextAsync(outputPath, json + Environment.NewLine, cancellationToken);
        await stdout.WriteLineAsync($"Wrote {ScopeScenarios.All.Count} scenarios (server {serverVersion}) to {outputPath}");
        return 0;
    }
}
