using System.CommandLine;
using System.Text.Json;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateCastMatrixCommand
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    public static Command Create()
    {
        var outputOption = new Option<string>("--output")
        {
            Description = "Path to write the matrix JSON to.",
            DefaultValueFactory = _ => "src/SilentScan.Core/Rules/CastMatrix.json",
        };

        var command = new Command("generate-cast-matrix", "Probe the Docker SQL Server oracle for what every explicit CAST and TRY_CAST between types keeps or loses, and the type unsized targets resolve to.");
        command.Options.Add(outputOption);

        command.SetAction(async (parseResult, cancellationToken) =>
        {
            var output = parseResult.GetValue(outputOption)!;
            return await RunAsync(output, SqlServerOptions.LocalDocker, Console.Out, cancellationToken);
        });

        return command;
    }

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var generator = new CastMatrixGenerator(sqlOptions);
        var (cells, resultTypes, serverVersion) = await generator.GenerateAsync(AssignMatrixGenerator.Types, AssignMatrixGenerator.Types, cancellationToken);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = DateTime.UtcNow.ToString("yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture),
            Notes = "Generated by SilentScan.Verify generate-cast-matrix against the local Docker SQL Server. "
                + "Each cell lists one outcome per probe value for CAST and TRY_CAST of a variable. Equal means the value cast back to the source type equals the original. "
                + "Loss means it differs with no error. Null means the result was NULL (TRY_CAST failure). Error:n means the engine raised message n. "
                + "ResultTypes gives the type CAST resolves for unsized or unusual targets, for a literal and for a variable operand.",
            Entries = cells,
            ResultTypes = resultTypes,
        };

        var json = JsonSerializer.Serialize(document, JsonOptions);
        await File.WriteAllTextAsync(outputPath, json + Environment.NewLine, cancellationToken);
        await stdout.WriteLineAsync($"Wrote {cells.Count} entries (server {serverVersion}) to {outputPath}");
        return 0;
    }
}
