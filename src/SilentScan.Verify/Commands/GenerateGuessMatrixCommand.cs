using System.CommandLine;
using SilentScan.Verify.Oracle;

namespace SilentScan.Verify.Commands;

public static class GenerateGuessMatrixCommand
{
    public static Command Create() =>
        MatrixCommandSupport.Create(
            "generate-guess-matrix",
            "Compile predicate shapes over a statistics-free table on the Docker SQL Server oracle and record the fraction of rows the optimizer guesses.",
            "src/SilentScan.Core/Rules/GuessMatrix.json",
            RunAsync);

    internal static async Task<int> RunAsync(string outputPath, SqlServerOptions sqlOptions, TextWriter stdout, CancellationToken cancellationToken = default)
    {
        var generator = new GuessMatrixGenerator(sqlOptions);
        var (cells, serverVersion) = await generator.GenerateAsync(cancellationToken);

        var document = new
        {
            ServerVersion = serverVersion,
            ProbedAtUtc = MatrixCommandSupport.ProbedAtUtc(),
            Notes = "Generated by SilentScan.Verify generate-guess-matrix against the local Docker SQL Server. "
                + "Each cell compiles SELECT filler FROM t WHERE <shape> over a heap with no column statistics whose cardinality is set to TableRows, and records estimated rows divided by TableRows. "
                + "Operand is a literal or an unsniffed variable; Estimator forces the default or the legacy cardinality estimation model. Error:n means the engine rejects the shape for that type.",
            GuessMatrixGenerator.TableRows,
            Entries = cells,
        };

        return await MatrixCommandSupport.WriteAsync(outputPath, document, cells.Count, serverVersion, stdout, cancellationToken);
    }
}
